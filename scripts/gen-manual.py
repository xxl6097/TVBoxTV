# 页脚连续页码。不足 60 页的全部提交；超过 60 页的同样提交前后各 30 页。
# 本手册按「一位没接触过这个软件的用户」的视角写：先讲装和启动，再按功能
# 逐个说明怎么点、点了会发生什么，配真实运行截图。

import os

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_BREAK
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor

SOFT_NAME = '夜帧影视软件'
SOFT_VER = 'V1.0'
DATE = '2026 年 11 月 4 日'

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHOT = os.path.join(ROOT, 'docs', 'store', 'screenshots')
OUT_DIR = os.path.join(ROOT, 'docs', 'copyright')
OUT = os.path.join(OUT_DIR, '夜帧影视_软件说明书.docx')

doc = Document()

# ---------- 页面与样式 ----------
sec = doc.sections[0]
sec.page_width, sec.page_height = Cm(21.0), Cm(29.7)
sec.top_margin = Cm(2.4)
sec.bottom_margin = Cm(2.2)
sec.left_margin = Cm(2.6)
sec.right_margin = Cm(2.4)

st = doc.styles['Normal']
st.font.name = '宋体'
st.font.size = Pt(11)
st.element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
st.paragraph_format.line_spacing = 1.45
st.paragraph_format.space_after = Pt(4)


def set_run(r, size=11, bold=False, color=None):
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.name = '宋体'
    r._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
    if color:
        r.font.color.rgb = RGBColor(*color)


def add_page_number(par):
    run = par.add_run()
    f1 = OxmlElement('w:fldChar'); f1.set(qn('w:fldCharType'), 'begin')
    it = OxmlElement('w:instrText'); it.set(qn('xml:space'), 'preserve'); it.text = 'PAGE'
    f2 = OxmlElement('w:fldChar'); f2.set(qn('w:fldCharType'), 'end')
    run._r.append(f1); run._r.append(it); run._r.append(f2)
    set_run(run, 9)


# 页眉：软件名称 + 版本
hp = sec.header.paragraphs[0]
hp.alignment = WD_ALIGN_PARAGRAPH.CENTER
set_run(hp.add_run('%s  %s   软件说明书' % (SOFT_NAME, SOFT_VER)), 9)
# 页脚：页码
fp = sec.footer.paragraphs[0]
fp.alignment = WD_ALIGN_PARAGRAPH.CENTER
add_page_number(fp)


def h1(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(16)
    p.paragraph_format.space_after = Pt(8)
    p.paragraph_format.keep_with_next = True
    set_run(p.add_run(text), 15, True)


def h2(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(4)
    p.paragraph_format.keep_with_next = True
    set_run(p.add_run(text), 12.5, True)


def para(text, indent=True):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.first_line_indent = Cm(0.74)
    set_run(p.add_run(text), 11)
    return p


def bullet(text):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.9)
    p.paragraph_format.first_line_indent = Cm(-0.35)
    set_run(p.add_run('· ' + text), 11)
    return p


def step(text):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.9)
    set_run(p.add_run(text), 11)
    return p


def shot(name, caption, width_cm=14.2):
    path = os.path.join(SHOT, name)
    if not os.path.exists(path):
        return
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(2)
    p.add_run().add_picture(path, width=Cm(width_cm))
    c = doc.add_paragraph()
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.paragraph_format.space_after = Pt(10)
    set_run(c.add_run(caption), 9.5, color=(0x55, 0x55, 0x55))


def icon_fig(name, caption, width_cm=3.6):
    """插入图标一类的独立图片（与 shot 的区别：路径在 docs/store 下，且尺寸小）。"""
    path = os.path.join(ROOT, 'docs', 'store', name)
    if not os.path.exists(path):
        print('  ! 缺图：%s' % name)
        return
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(2)
    p.add_run().add_picture(path, width=Cm(width_cm))
    c = doc.add_paragraph()
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.paragraph_format.space_after = Pt(10)
    set_run(c.add_run(caption), 9.5, color=(0x55, 0x55, 0x55))


def page_break():
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


